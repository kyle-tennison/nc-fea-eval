#!/usr/bin/env bash
# Sets up the fea-eval dispatcher on this machine as a service that starts on boot and restarts on crash.
# Re-run it any time (e.g. after `git pull`) to rebuild the image, reinstall, and restart.
#
#   hosting/dispatch/deploy/install.sh                      # asks for the worker token the first time
#   FEA_WORKER_TOKEN=... hosting/dispatch/deploy/install.sh
#
# The token is FEA_WORKER_TOKEN in /etc/fea-proxy.env on the proxy. With sudo this installs a system
# service; without it, a user service kept running across logouts and reboots by lingering.
# Override the choice with FEA_MODE=system|user.
set -euo pipefail

PROXY_URL="${FEA_PROXY_URL:-https://52-37-243-198.sslip.io}"
IMAGE="${FEA_IMAGE:-fea-eval}"
SERVICE=fea-dispatch
DISPATCH_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
REPO_ROOT="$(cd "$DISPATCH_DIR/../.." && pwd)"

say() { printf '\033[1m==> %s\033[0m\n' "$*"; }
warn() { printf '\033[33mwarning:\033[0m %s\n' "$*" >&2; }
die() { printf '\033[31merror:\033[0m %s\n' "$*" >&2; exit 1; }

# --- preflight ---

[[ $EUID -ne 0 ]] || die "run this as the user the service should run as, not with sudo (it asks when needed)"
[[ $(uname -s) == Linux ]] || die "this installs a systemd service; run it on the Linux machine"
command -v systemctl >/dev/null || die "systemd not found"
command -v docker >/dev/null || die "docker not found; install it first"
docker info >/dev/null 2>&1 || die "$USER can't reach Docker (add yourself to the docker group and log in again)"

MODE="${FEA_MODE:-}"
if [[ -z $MODE ]]; then
    if sudo -n true 2>/dev/null || { [[ -t 0 ]] && sudo -v 2>/dev/null; }; then MODE=system; else MODE=user; fi
fi
if [[ $MODE == system ]]; then
    SUDO=sudo
    CTL=(sudo systemctl)
    ENV_FILE=/etc/fea-dispatch.env
    UNIT_FILE=/etc/systemd/system/$SERVICE.service
    TARGET=multi-user.target
elif [[ $MODE == user ]]; then
    SUDO=
    CTL=(systemctl --user)
    ENV_FILE=$HOME/.config/fea-dispatch.env
    UNIT_FILE=$HOME/.config/systemd/user/$SERVICE.service
    TARGET=default.target
else
    die "FEA_MODE must be system or user"
fi
say "Installing as a $MODE service from $REPO_ROOT"

if ! command -v uv >/dev/null; then
    export PATH="$HOME/.local/bin:$PATH"
    if ! command -v uv >/dev/null; then
        say "Installing uv"
        curl -LsSf https://astral.sh/uv/0.8.4/install.sh | env UV_NO_MODIFY_PATH=1 sh
    fi
fi

# --- build ---

say "Building the $IMAGE image (slow the first time)"
docker build --tag "$IMAGE" "$REPO_ROOT"

say "Installing the dispatcher"
(cd "$DISPATCH_DIR" && uv sync --frozen --no-dev --python 3.12)

# --- config ---

if ! $SUDO test -f "$ENV_FILE"; then
    token="${FEA_WORKER_TOKEN:-}"
    if [[ -z $token ]]; then
        [[ -t 0 ]] || die "set FEA_WORKER_TOKEN (it's in /etc/fea-proxy.env on the proxy)"
        read -rsp "Worker token (FEA_WORKER_TOKEN in /etc/fea-proxy.env on the proxy): " token
        echo
    fi
    [[ -n $token ]] || die "empty token"
    say "Writing $ENV_FILE"
    $SUDO mkdir -p "$(dirname "$ENV_FILE")"
    printf 'FEA_PROXY_URL=%s\nFEA_WORKER_TOKEN=%s\nFEA_IMAGE=%s\n' "$PROXY_URL" "$token" "$IMAGE" |
        (umask 077 && $SUDO tee "$ENV_FILE" >/dev/null)
fi

# A heartbeat for a job that doesn't exist: 409 means the token was accepted, 401 means it wasn't.
url="$($SUDO sed -n 's/^FEA_PROXY_URL=//p' "$ENV_FILE")"
token="$($SUDO sed -n 's/^FEA_WORKER_TOKEN=//p' "$ENV_FILE")"
code="$(curl -s -o /dev/null -w '%{http_code}' -m 15 -X POST -H @<(printf 'Authorization: Bearer %s\n' "$token") \
    -H "X-Lease: install-check" "$url/worker/jobs/install-check/heartbeat" || true)"
case $code in
    409) say "Proxy at $url accepted the token" ;;
    401 | 403) die "the proxy rejected the worker token; fix it in $ENV_FILE and re-run" ;;
    *) warn "couldn't check the token against $url (HTTP ${code:-none}); installing anyway" ;;
esac
unset token

# --- service ---

say "Installing $UNIT_FILE"
$SUDO mkdir -p "$(dirname "$UNIT_FILE")"
$SUDO tee "$UNIT_FILE" >/dev/null <<EOF
# Generated by $DISPATCH_DIR/deploy/install.sh; re-run that instead of editing this.
[Unit]
Description=fea-eval dispatcher
After=network-online.target docker.service
Wants=network-online.target

[Service]
${SUDO:+User=$USER}
WorkingDirectory=$DISPATCH_DIR
EnvironmentFile=$ENV_FILE
ExecStart=$DISPATCH_DIR/.venv/bin/fea-dispatch
Restart=always
RestartSec=5

[Install]
WantedBy=$TARGET
EOF

"${CTL[@]}" daemon-reload
"${CTL[@]}" enable "$SERVICE" >/dev/null
"${CTL[@]}" restart "$SERVICE"

if [[ $MODE == system ]]; then
    systemctl is-enabled docker >/dev/null 2>&1 || warn "docker.service isn't enabled, so jobs will fail after a reboot until it starts (sudo systemctl enable docker)"
elif ! loginctl enable-linger "$USER" 2>/dev/null; then
    warn "couldn't enable lingering, so the service stops when you log out and won't start on boot; ask IT to run: loginctl enable-linger $USER"
fi

sleep 3
if "${CTL[@]}" is-active --quiet "$SERVICE"; then
    say "$SERVICE is running and will start on boot"
else
    warn "$SERVICE isn't running; recent logs:"
fi
if [[ $MODE == system ]]; then journal=(sudo journalctl); else journal=(journalctl --user); fi
"${journal[@]}" -u "$SERVICE" -n 5 --no-pager || true
echo "Logs: ${journal[*]} -u $SERVICE -f"
